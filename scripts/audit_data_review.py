"""Reproduce the local data review without modifying source data or notebooks.

Run from the repo: python scripts/audit_data_review.py
Writes docs/data_audit.json and docs/data_dictionary.md.
"""
from pathlib import Path
import hashlib
import json
import sys

import duckdb
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
P = ROOT / "data/processed"
DOCS = ROOT / "docs"


def main():
    DOCS.mkdir(exist_ok=True)
    con = duckdb.connect()
    audit = {"scope": "All local processed files; no upstream refresh", "duckdb": duckdb.__version__,
             "notebook_sha256": hashlib.sha256((ROOT / "notebooks/03_eda_storm_outage.ipynb").read_bytes()).hexdigest()}
    dictionary = ["# Local data dictionary", "", "Generated by `python scripts/audit_data_review.py`. Null counts describe stored cells, not absent records. Repeated annual files are grouped by dataset. CSV fields are read as text to preserve identifiers; VARCHAR for these files is an audit parsing choice, not a declaration that numeric values are nonnumeric. This is a mechanical field inventory; see [the guide](data_review.md) for interpretation.", ""]
    inventory = []
    groups = {}
    for p in sorted(P.rglob("*")):
        if p.suffix not in {".csv", ".parquet"}:
            continue
        rel = p.relative_to(P).as_posix()
        inventory.append({"file": rel, "bytes": p.stat().st_size, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()})
        key = "eaglei/outages_YYYY.parquet" if p.name.startswith("outages_") else "storms/storm_events_YYYY.parquet" if p.name.startswith("storm_events_") else rel
        groups.setdefault(key, []).append(p.as_posix())
    audit["inventory"] = inventory
    for key, files in groups.items():
        relation = con.read_csv(files, all_varchar=True) if key.endswith(".csv") else con.read_parquet(files)
        relation.create_view("profile", replace=True)
        cols = relation.columns
        quoted = ['"' + c.replace('"', '""') + '"' for c in cols]
        n = con.sql("select count(*) from profile").fetchall()[0][0]
        counts = con.sql("select " + ",".join(f"count(*) - count({c})" for c in quoted) + " from profile").fetchall()[0]
        dictionary += [f"## {key}", "", f"{len(files)} file(s); {n:,} rows.", "", "| Field | Stored type | Null cells | Null % |", "| --- | --- | ---: | ---: |"]
        for c, typ, null in zip(cols, relation.types, counts):
            dictionary.append(f"| `{c}` | {typ} | {null:,} | {100*null/n:.2f}% |")
        dictionary.append("")
    def query(sql):
        return con.sql(sql).df().to_dict("records")
    out = (P / "eaglei/outages_*.parquet").as_posix()
    storms = (P / "storms/storm_events_*.parquet").as_posix()
    mapped = (P / "storms/storm_event_counties.parquet").as_posix()
    census = (P / "reference/county_census.parquet").as_posix()
    con.sql(f"create view o as select * from '{out}'")
    con.sql(f"create view s as select * from '{storms}'")
    con.sql(f"create view m as select * from '{mapped}'")
    con.sql(f"create view c as select * from '{census}'")
    audit["outages_year"] = query("""select year(run_start_time) as year, count(*) as rows,
      count(distinct fips_code) counties, min(run_start_time) first, max(run_start_time) last,
      count(*) filter(where customers_out is null) nulls,
      count(*) filter(where customers_out=0) zeros, max(customers_out) maximum,
      count(*) filter(where customers_out<0) negative,
      count(*) filter(where customers_out%1 != 0) fractional,
      count(*) filter(where minute(run_start_time)%15 !=0) odd_minutes
      from o group by all order by year""")
    audit["outage_integrity"] = query("""select count(*) as rows, count(distinct fips_code) counties,
      count(*) - count(distinct (fips_code,run_start_time)) duplicate_keys,
      count(*) filter(where fips_code is null or run_start_time is null) null_keys from o""")
    audit["never_observed_counties"] = query("select distinct fips_code,county_name from c anti join (select distinct fips_code from o) using(fips_code)")
    audit["storms_year"] = query("select year,count(*) events,count(distinct episode_id) episodes from s group by all order by year")
    audit["storms_integrity"] = query("""select count(*) events,count(distinct event_id) unique_events,
      count(distinct event_type) event_types,
      count(*) filter(where begin_utc is null or end_utc is null) null_times,
      count(*) filter(where end_utc<begin_utc) reversed_times from s""")
    audit["storm_types"] = query("select event_type,count(*) events,count(magnitude) magnitude_present from s group by all order by events desc")
    audit["mapping"] = query("select cz_type,count(*) n,count(*) filter(where event_id not in (select event_id from m)) unmapped from s group by all")
    audit["unmapped_types"] = query("select event_type,count(*) n from s anti join (select distinct event_id from m) using(event_id) group by all order by n desc")
    audit["bad_counties"] = query("select state_abbr,event_type,count(*) n from m anti join (select distinct fips_code from c) using(fips_code) group by all")
    audit["mapped_integrity"] = query("select count(*) as rows,count(distinct event_id) events,count(*)-count(distinct(event_id,fips_code)) duplicate_keys from m")
    audit["census"] = query("""select acs_year,count(*) as rows,count(distinct fips_code) counties,
      count(*) filter(where population<=0 or housing_units<=0 or land_sqmi<=0) nonpositive,
      count(*) filter(where population is null or housing_units is null or land_sqmi is null) missing
      from c group by all order by acs_year""")
    mcc = pd.read_csv(P / "eaglei/MCC.csv", dtype={"County_FIPS": str})
    mcc["fips_code"] = mcc.County_FIPS.str.zfill(5)
    con.register("mcc", mcc)
    audit["mcc"] = query("""select left(c.fips_code,2) state_fips,count(*) counties,count(Customers) mcc_present,
      median(Customers/housing_units) median_customers_per_housing_unit,
      count(*) filter(where Customers/housing_units<0.5) below_half
      from c left join mcc using(fips_code) where acs_year=2023 group by all order by state_fips""")
    audit["mcc_missing"] = query("select fips_code,county_name from c anti join mcc using(fips_code) where acs_year=2023")
    zone = pd.read_parquet(P / "reference/zone_county.parquet")
    coverage = pd.read_csv(P / "eaglei/coverage_history.csv")
    dqi = pd.read_csv(P / "eaglei/DQI.csv")
    audit["reference_integrity"] = {
        "census_duplicate_keys": query("select count(*)-count(distinct(fips_code,acs_year)) n from c")[0]["n"],
        "mcc_duplicate_keys": int(mcc.fips_code.duplicated().sum()),
        "zone_duplicate_keys": int(zone.duplicated(["state", "zone", "fips_code"]).sum()),
        "coverage_duplicate_keys": int(coverage.duplicated(["state", "year"]).sum()),
        "dqi_duplicate_keys": int(dqi.duplicated(["fema", "year"]).sum()),
    }
    audit["study_coverage"] = coverage[coverage.state.isin(["AL","FL","GA","NC","SC","TN"])].to_dict("records")
    audit["region4_dqi"] = dqi[dqi.fema.eq(4)].to_dict("records")
    from src.eda import build_storm_outage_tables
    nc = duckdb.connect()
    build_storm_outage_tables(nc, out, mapped, census)
    audit["notebook_join_note"] = "Uses src.eda.build_storm_outage_tables; unknown outcomes remain null; rates exclude unknown windows."
    def nq(sql):
        return nc.sql(sql).df().to_dict("records")
    audit["joined_year"] = nq("select year,count(*) as rows,count(*) filter(where peak_hr is null) no_observed_peak,count(*) filter(where major) major from imp group by all order by year")
    audit["joined_type"] = nq("select event_type,count(*) as rows,median(peak_share) median_share,avg(major::int) major_rate,count(*) filter(where peak_hr is null) no_observed_peak from imp group by all order by major_rate desc")
    audit["window_observations"] = nq("""with w as (
      select event_id,fips_code,unnest(generate_series(w0,w1,interval 1 hour)) hr from ev),
      a as (select event_id,fips_code,count(*) expected,count(h.out) observed
      from w left join hourly h using(fips_code,hr) group by all)
      select count(*) as windows,count(*) filter(where observed=0) unobserved,
      count(*) filter(where observed=expected) fully_observed,
      median(observed::double/expected) median_observed_fraction from a""")
    audit["overlap"] = nq("""with w as (select fips_code,unnest(generate_series(w0,w1,interval 1 hour)) hr from ev),
      g as (select fips_code,hr,count(*) n from w group by all)
      select count(*) distinct_county_hours,count(*) filter(where n>1) shared_county_hours,max(n) max_events_per_hour from g""")
    audit["capping"] = nq(f"""with a as (select fips_code,date_trunc('hour',run_start_time) hr,median(customers_out) out
      from '{out}' where customers_out is not null group by all)
      select count(*) observed_hours,count(*) filter(where a.out>cust_est) capped_hours
      from a join cust c on a.fips_code=c.fips_code and c.acs_year=least(year(a.hr),2024)""")
    audit["raw_inventory"] = [{"file": p.relative_to(ROOT).as_posix(), "bytes": p.stat().st_size} for p in sorted((ROOT / "data/raw").rglob("*")) if p.is_file()]
    (DOCS / "data_audit.json").write_text(json.dumps(audit, indent=2, default=str)+"\n", encoding="utf-8")
    (DOCS / "data_dictionary.md").write_text("\n".join(dictionary), encoding="utf-8")
    print(json.dumps({k:v for k,v in audit.items() if k not in {"inventory","raw_inventory"}}, indent=2, default=str))


if __name__ == "__main__":
    main()
